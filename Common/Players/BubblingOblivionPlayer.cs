using KyoMod.Content.Buffs;
using KyoMod.Content.Items.Magic.BubblingOblivion;
using KyoMod.Content.Projectiles.Magic.BubblingOblivion;
using Microsoft.Xna.Framework;
using Terraria;
using Terraria.GameInput;
using Terraria.ModLoader;

namespace KyoMod.Common.Players
{
    public class BubblingOblivionPlayer : ModPlayer
    {
        // "Liberation Energy" — same shared name/resource shape as CryingTidesPlayer's own pool (design
        // doc §8: every weapon in the mod shares the name, but gets its own separate pocket). Unlike
        // CryingTides' Spectro/Havoc split cost, Bubbling Oblivion's two forms are meant to deal the
        // same baseline DPS (§2) — the ultimate is symmetric, one flat cost for either direction.
        //
        // Placeholder values: exact numbers are explicitly still open (§10 — "Damage numbers, mana
        // costs, and Liberation Energy cost for Bubbling Oblivion's ultimate specifically"). Picked to
        // be roughly in CryingTides' own range rather than guessed from nothing.
        public float LiberationEnergy = 0f;
        public const float MaxLiberationEnergy = 60f;
        public const float UltimateCost = 1f; // TESTING — was 60, temporarily lowered to iterate on the ult faster
        public const float EnergyPerHit = 1f;

        // Void Stacks / Bubble Stacks (§5) — cross-form currency generated by casting the CURRENT
        // form's skill, spent in the OTHER form. Nothing increments these yet: skills don't exist until
        // PostWoF (§9), so both stay 0 until that's built in a later session. Wired in now because the
        // ultimate's own buff-sizing logic (§7.4) already needs to read them.
        public int VoidStacks = 0;
        public int BubbleStacks = 0;

        // How many stacks the most recently granted BubblingOblivionFormBuff was sized by — read by
        // that buff once it actually has a stat payoff (not yet implemented, see its own header).
        public int FormBuffPotency = 0;
        private const int FormBuffDuration = 600; // 10s, placeholder alongside the cost/energy values above

        public void AddLiberationEnergy(float amount = EnergyPerHit)
        {
            LiberationEnergy = System.Math.Min(LiberationEnergy + amount, MaxLiberationEnergy);
        }

        // Gated on the generic HasUltimate flag (true starting PostEvilBoss, §9) rather than a
        // hardcoded tier check, same pattern as CryingTidesPlayer's own ProcessTriggers. A denied
        // attempt (not enough energy) is simply ignored — cost is only spent once the cast actually
        // fires, not on keypress.
        public override void ProcessTriggers(TriggersSet triggersSet)
        {
            if (!KyoMod.CryingTidesUltimateKeybind.JustPressed) return;
            if (Player.HeldItem?.ModItem is not BubblingOblivionBase staff || !staff.HasUltimate) return;
            if (LiberationEnergy < UltimateCost) return;

            LiberationEnergy -= UltimateCost;

            bool wasVoid = staff.ActiveForm == 1;
            int damage = Player.GetWeaponDamage(staff.Item);

            if (!wasVoid)
            {
                // Bubble -> Void: the redesigned cast — a black hole appears at the cursor, lingers
                // dealing contact damage for ~2s, then explodes for 10x (BubblingOblivionVoidBlackHole
                // owns the full timeline/damage). Replaces the old radial bolt burst for this direction
                // only — Void -> Bubble keeps that placeholder below until a symmetric Bubble-themed
                // version of this same idea is designed.
                Projectile.NewProjectile(Player.GetSource_Misc("BubblingOblivionUltimate"), Main.MouseWorld, Vector2.Zero,
                    ModContent.ProjectileType<BubblingOblivionVoidBlackHole>(), damage, staff.Item.knockBack, Player.whoAmI);
            }
            else
            {
                // Void -> Bubble: still the original placeholder — "a burst of damage in the current
                // form" (§7.2) as a radial volley of the current form's own regular bolt (Void-tinted,
                // since we're leaving Void), fired before the switch itself.
                const int burstCount = 8;
                const float burstSpeed = 9f;
                for (int i = 0; i < burstCount; i++)
                {
                    Vector2 dir = (MathHelper.TwoPi * i / burstCount).ToRotationVector2();
                    int boltIndex = Projectile.NewProjectile(Player.GetSource_Misc("BubblingOblivionUltimate"), Player.Center, dir * burstSpeed,
                        ModContent.ProjectileType<BubblingOblivionBolt>(), damage, staff.Item.knockBack, Player.whoAmI, 3f, 3f);
                    if (Main.projectile[boltIndex].ModProjectile is BubblingOblivionBolt bolt)
                        bolt.IsVoidVariant = true;
                }
            }

            // Buff sized by whatever's banked in the form just left (§7.4) — see BubblingOblivionFormBuff's
            // own header for why this doesn't do anything numeric yet.
            FormBuffPotency = wasVoid ? BubbleStacks : VoidStacks;
            Player.AddBuff(ModContent.BuffType<BubblingOblivionFormBuff>(), FormBuffDuration);

            // The switch itself — permanent until ulted again (§7.5), not a timed burst.
            staff.ActiveForm = wasVoid ? 0 : 1;
        }
    }
}
